//! Host scan for the setup wizard (ADR-0001 D5, D6): which launchd
//! services each Homebrew package affects, and which need root.
//!
//! Links come from a service's program path, the virtual environment it
//! runs in, Homebrew paths in its arguments, or Homebrew paths inside a
//! wrapper script it starts. From a script only `<prefix>/bin/<name>` and
//! `<prefix>/opt/<name>` tokens are kept; no other line leaves this module.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::exec::Runner;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Via {
    Program,
    Venv,
    Arguments,
    Script,
}

impl Via {
    pub fn describe(self) -> &'static str {
        match self {
            Via::Program => "runs it directly",
            Via::Venv => "Python environment built on it",
            Via::Arguments => "named in its arguments",
            Via::Script => "named in its start script",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Service {
    pub label: String,
    pub plist: PathBuf,
    /// Defined in /Library/LaunchDaemons: restarting it needs root.
    pub root: bool,
    /// Kept running (KeepAlive), as opposed to a scheduled job.
    pub keep_alive: bool,
    /// Loaded in launchd now. Plists left behind by a move are not.
    pub loaded: bool,
    pub program: String,
    /// `(package, how the link was found)`, sorted.
    pub links: Vec<(String, Via)>,
    /// The venv's interpreter, when the service runs in one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub venv_python: Option<PathBuf>,
}

#[derive(Debug, Default, Serialize)]
pub struct Scan {
    pub services: Vec<Service>,
    /// Plist files that could not be read, so they are not reported as
    /// new on every run.
    pub skipped: Vec<PathBuf>,
    pub warnings: Vec<String>,
}

/// The saved scan, `services.toml` next to the overrides file. Setup
/// writes it and `setup --rescan` refreshes it; nobody edits it by hand.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ServiceMap {
    pub scanned: String,
    /// The user's numeric id, for `launchctl kickstart gui/<uid>/<label>`.
    pub uid: String,
    #[serde(default)]
    pub skipped: Vec<PathBuf>,
    #[serde(default, rename = "service")]
    pub services: Vec<Service>,
}

const MAP_HEADER: &str = "# Generated by `guarded-update setup`. Do not edit: run\n# `guarded-update setup --rescan` to refresh it, and put your own\n# service settings in the base config.\n\n";

impl ServiceMap {
    pub fn from_scan(scan: Scan, uid: &str, scanned: &str) -> Self {
        Self {
            scanned: scanned.to_string(),
            uid: uid.to_string(),
            skipped: scan.skipped,
            services: scan.services,
        }
    }

    /// `None` when the file does not exist yet.
    pub fn load(path: &Path) -> Result<Option<Self>, String> {
        let text = match std::fs::read_to_string(path) {
            Ok(text) => text,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            Err(e) => return Err(format!("cannot read {}: {e}", path.display())),
        };
        toml::from_str(&text).map(Some).map_err(|e| {
            format!(
                "{} is not valid; run `guarded-update setup --rescan` to rebuild it: {e}",
                path.display()
            )
        })
    }

    pub fn save(&self, path: &Path) -> Result<(), String> {
        let body =
            toml::to_string(self).map_err(|e| format!("cannot write the service list: {e}"))?;
        crate::state::write_private(path, &format!("{MAP_HEADER}{body}"))
    }

    /// Plist files added and removed since the scan, from a directory
    /// listing alone, so checking costs no `plutil` calls.
    pub fn changes(&self, now: &[(PathBuf, bool)]) -> (Vec<PathBuf>, Vec<PathBuf>) {
        let known: BTreeSet<&Path> = self
            .services
            .iter()
            .map(|s| s.plist.as_path())
            .chain(self.skipped.iter().map(PathBuf::as_path))
            .collect();
        let current: BTreeSet<&Path> = now.iter().map(|(p, _)| p.as_path()).collect();
        let added = current
            .difference(&known)
            .map(|p| p.to_path_buf())
            .collect();
        let removed = known
            .difference(&current)
            .map(|p| p.to_path_buf())
            .collect();
        (added, removed)
    }
}

/// Restart and health commands for a scanned service, worked out when
/// needed rather than written to any file.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Defaults {
    pub restart: Vec<String>,
    pub health: Vec<String>,
    pub health_expect: Option<String>,
}

pub fn defaults_for(service: &Service, uid: &str) -> Defaults {
    if service.root {
        return Defaults::default();
    }
    let label = &service.label;
    let strings = |items: &[&str]| items.iter().map(|s| (*s).to_string()).collect::<Vec<_>>();
    if service.keep_alive {
        Defaults {
            restart: strings(&[
                "launchctl",
                "kickstart",
                "-k",
                &format!("gui/{uid}/{label}"),
            ]),
            health: strings(&["launchctl", "list", label]),
            health_expect: Some("\"PID\"".into()),
        }
    } else {
        Defaults {
            restart: Vec::new(),
            health: strings(&["launchctl", "list", label]),
            health_expect: None,
        }
    }
}

/// Where the scan reads from; a fake in tests.
pub trait Source {
    /// `(plist path, defined for root)`.
    fn plist_files(&self) -> Vec<(PathBuf, bool)>;
    fn label(&self, plist: &Path) -> Result<String, String>;
    /// `ProgramArguments`, or `[Program]`.
    fn arguments(&self, plist: &Path) -> Result<Vec<String>, String>;
    fn keep_alive(&self, plist: &Path) -> bool;
    /// Whether launchd has the service loaded for this user.
    fn loaded(&self, label: &str) -> bool;
    fn canonicalize(&self, path: &Path) -> Option<PathBuf>;
    /// A small text file (pyvenv.cfg or a start script), or `None`.
    fn read_text(&self, path: &Path) -> Option<String>;
}

/// `<prefix>/Cellar/<f>/...` -> `f`, `<prefix>/Caskroom/<c>/...` -> `c`,
/// `<prefix>/opt/<n>/...` -> `n`.
pub fn package_from_path(prefix: &str, path: &Path) -> Option<String> {
    let rest = path.strip_prefix(prefix).ok()?;
    let mut parts = rest.components().map(|c| c.as_os_str().to_string_lossy());
    match (parts.next()?.as_ref(), parts.next()) {
        ("Cellar" | "Caskroom" | "opt", Some(name)) if !name.is_empty() => Some(name.into_owned()),
        _ => None,
    }
}

fn is_name_char(c: char) -> bool {
    c.is_ascii_alphanumeric() || matches!(c, '@' | '.' | '_' | '+' | '-')
}

/// `<prefix>/bin/<x>` and `<prefix>/opt/<x>` tokens in text, in order.
pub fn homebrew_tokens(prefix: &str, text: &str) -> Vec<String> {
    let mut found = Vec::new();
    for dir in ["bin", "opt"] {
        let needle = format!("{prefix}/{dir}/");
        let mut rest = text;
        while let Some(at) = rest.find(&needle) {
            let after = &rest[at + needle.len()..];
            let name: String = after.chars().take_while(|c| is_name_char(*c)).collect();
            if !name.is_empty() {
                found.push((text.len() - rest.len() + at, format!("{needle}{name}")));
            }
            rest = &after[name.len()..];
        }
    }
    found.sort();
    let mut seen = BTreeSet::new();
    found
        .into_iter()
        .filter_map(|(_, token)| seen.insert(token.clone()).then_some(token))
        .collect()
}

fn resolve(source: &dyn Source, prefix: &str, path: &Path) -> Option<String> {
    package_from_path(prefix, path).or_else(|| {
        let real = source.canonicalize(path)?;
        package_from_path(prefix, &real)
    })
}

fn venv_base(source: &dyn Source, prefix: &str, program: &Path) -> Option<(String, PathBuf)> {
    let bin = program.parent()?;
    if bin.file_name()? != "bin" {
        return None;
    }
    let root = bin.parent()?;
    let cfg = source.read_text(&root.join("pyvenv.cfg"))?;
    let home = cfg.lines().find_map(|line| {
        let (key, value) = line.split_once('=')?;
        (key.trim() == "home").then(|| value.trim().to_string())
    })?;
    let package = resolve(source, prefix, Path::new(&home))?;
    Some((package, bin.join("python")))
}

pub fn scan(source: &dyn Source, prefix: &str, home: &Path) -> Scan {
    let mut result = Scan::default();
    for (plist, root) in source.plist_files() {
        let shown = plist.display();
        let label = match source.label(&plist) {
            Ok(label) if !label.is_empty() => label,
            Ok(_) => {
                result.warnings.push(format!("skipped {shown}: no Label"));
                result.skipped.push(plist.clone());
                continue;
            }
            Err(e) => {
                result.warnings.push(format!("skipped {shown}: {e}"));
                result.skipped.push(plist.clone());
                continue;
            }
        };
        let args = match source.arguments(&plist) {
            Ok(args) if !args.is_empty() => args,
            Ok(_) | Err(_) => {
                result
                    .warnings
                    .push(format!("skipped {shown}: no program to run"));
                result.skipped.push(plist.clone());
                continue;
            }
        };
        let program = PathBuf::from(&args[0]);
        let mut links: Vec<(String, Via)> = Vec::new();
        let mut venv_python = None;
        if let Some(package) = resolve(source, prefix, &program) {
            links.push((package, Via::Program));
        }
        if let Some((package, python)) = venv_base(source, prefix, &program) {
            links.push((package, Via::Venv));
            venv_python = Some(python);
        }
        for token in homebrew_tokens(prefix, &args[1..].join(" ")) {
            if let Some(package) = resolve(source, prefix, Path::new(&token)) {
                links.push((package, Via::Arguments));
            }
        }
        if program.starts_with(home)
            && venv_python.is_none()
            && let Some(text) = source.read_text(&program)
        {
            for token in homebrew_tokens(prefix, &text) {
                if let Some(package) = resolve(source, prefix, Path::new(&token)) {
                    links.push((package, Via::Script));
                }
            }
        }
        // This user cannot list root daemons; assume they are loaded.
        let loaded = root || source.loaded(&label);
        // One link per package, keeping the most direct way it was found.
        links.sort();
        links.dedup_by(|a, b| a.0 == b.0);
        result.services.push(Service {
            label,
            keep_alive: source.keep_alive(&plist),
            loaded,
            plist,
            root,
            program: args[0].clone(),
            links,
            venv_python,
        });
    }
    result.services.sort_by(|a, b| a.label.cmp(&b.label));
    result
}

/// The real host: launchd plists read with `plutil`, files with std.
pub struct HostSource<'a> {
    pub runner: &'a dyn Runner,
    pub home: PathBuf,
}

const MAX_TEXT_BYTES: u64 = 256 * 1024;

impl HostSource<'_> {
    fn extract(&self, plist: &Path, key: &str, format: &str) -> Result<String, String> {
        let path = plist.to_string_lossy();
        let out = self
            .runner
            .run("plutil", &["-extract", key, format, "-o", "-", &path], &[])?;
        if out.success() {
            Ok(out.stdout.trim_end_matches('\n').to_string())
        } else {
            Err("not a valid plist or key missing".into())
        }
    }
}

/// launchd plist files, `(path, defined for root)`: a directory listing
/// only, so it is cheap enough to run before every command.
pub fn plist_files(home: &Path) -> Vec<(PathBuf, bool)> {
    let dirs = [
        (home.join("Library/LaunchAgents"), false),
        (PathBuf::from("/Library/LaunchAgents"), false),
        (PathBuf::from("/Library/LaunchDaemons"), true),
    ];
    let mut files = Vec::new();
    for (dir, root) in dirs {
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.filter_map(Result::ok) {
            let path = entry.path();
            if path.extension().is_some_and(|x| x == "plist") {
                files.push((path, root));
            }
        }
    }
    files.sort();
    files
}

impl Source for HostSource<'_> {
    fn plist_files(&self) -> Vec<(PathBuf, bool)> {
        plist_files(&self.home)
    }

    fn label(&self, plist: &Path) -> Result<String, String> {
        self.extract(plist, "Label", "raw")
    }

    fn arguments(&self, plist: &Path) -> Result<Vec<String>, String> {
        match self.extract(plist, "ProgramArguments", "json") {
            Ok(json) => serde_json::from_str(&json).map_err(|e| e.to_string()),
            Err(_) => self.extract(plist, "Program", "raw").map(|p| vec![p]),
        }
    }

    fn keep_alive(&self, plist: &Path) -> bool {
        // `true`, or a dictionary of conditions, both keep it running.
        match self.extract(plist, "KeepAlive", "json") {
            Ok(value) => value != "false",
            Err(_) => false,
        }
    }

    fn loaded(&self, label: &str) -> bool {
        self.runner
            .run("launchctl", &["list", label], &[])
            .is_ok_and(|o| o.success())
    }

    fn canonicalize(&self, path: &Path) -> Option<PathBuf> {
        std::fs::canonicalize(path).ok()
    }

    fn read_text(&self, path: &Path) -> Option<String> {
        let meta = std::fs::metadata(path).ok()?;
        if !meta.is_file() || meta.len() > MAX_TEXT_BYTES {
            return None;
        }
        std::fs::read_to_string(path).ok()
    }
}

